#!/usr/bin/env python3
"""Generate the shared Hot Dogs snippet on its original 16 x 1.752 s grid."""
import argparse
from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from choreography import Stage, pose

PHRASE_S = 1.752
SUBDIVISION_S = PHRASE_S / 4


def make_stage():
    # 'Beat' here is the existing choreography grid, not a measured audio BPM.
    stage = Stage(bpm=60 / SUBDIVISION_S, amplitude=1)

    def groove(side, intensity=1):
        # Head looks first; torso follows, compresses on the accent, then rebounds.
        stage.cue(head={'yaw': -side * 16, 'pitch': -5},
                  body={'y': side * 0.005, 'z': -0.003})
        stage.cue(head={'yaw': -side * 12, 'pitch': 3},
                  turn={'yaw': side * 5, 'roll': -side * 3},
                  body={'y': side * 0.012 * intensity, 'z': -0.007})
        stage.cue(head={'yaw': -side * 8, 'pitch': 9},
                  turn={'yaw': side * 3, 'roll': -side * 4},
                  body={'y': side * 0.009, 'z': -0.012})
        stage.cue(head={'yaw': side * 4, 'pitch': -3},
                  body={'y': side * 0.003, 'z': -0.002})

    def foot_accent(leg, side):
        # Only one toe lifts. Keep a small torso bias away from it until landing.
        front = leg.endswith('front')
        rear = leg.endswith('back')
        bias = {'x': -0.01 if front else (0.01 if rear else 0), 'y': -side * 0.008, 'z': -0.005}
        stage.cue(body=bias, head={'yaw': side * 12, 'pitch': -5},
                  feet={leg: {'z': 0.02}})
        stage.cue(body=bias, head={'yaw': -side * 10, 'pitch': 7},
                  turn={'yaw': -side * 3},
                  feet={leg: {'z': 0.02, 'x': 0.016 if front else (-0.012 if rear else 0),
                              'y': side * 0.012}})
        stage.cue(body=bias, head={'yaw': side * 6, 'pitch': -3},
                  feet={leg: {'z': 0.02}})
        stage.cue(body=bias, head={'pitch': 5})

    with stage.section('01_look_left'):
        groove(1)
    with stage.section('02_look_right'):
        groove(-1)
    with stage.section('03_right_front_kick'):
        foot_accent('right_front', -1)
    with stage.section('04_left_front_answer'):
        foot_accent('left_front', 1)
    with stage.section('05_twist_left'):
        groove(1, 1.2)
    with stage.section('06_twist_right'):
        groove(-1, 1.2)
    with stage.section('07_right_side_tap'):
        foot_accent('right_mid', -1)
    with stage.section('08_left_side_tap'):
        foot_accent('left_mid', 1)
    with stage.section('09_body_wave'):
        for pitch, head, x, z in ((-3, -8, -0.008, -0.003), (2, 8, 0.008, -0.009),
                                  (4, 12, 0.012, -0.012), (0, -4, 0, -0.003)):
            stage.cue(turn={'pitch': pitch}, head={'pitch': head}, body={'x': x, 'z': z})
    with stage.section('10_shoulder_roll'):
        for roll, pitch in ((-4, -2), (-2, 4), (4, 2), (2, -3)):
            stage.cue(turn={'roll': roll, 'pitch': pitch},
                      head={'roll': -roll, 'pitch': -pitch * 2}, body={'z': -0.006})
    with stage.section('11_right_back_flick'):
        foot_accent('right_back', -1)
    with stage.section('12_left_back_flick'):
        foot_accent('left_back', 1)
    with stage.section('13_encore_left'):
        groove(1, 1.2)
    with stage.section('14_encore_right'):
        groove(-1, 1.2)
    with stage.section('15_double_nod'):
        for pitch, z in ((-8, -0.003), (12, -0.012), (-6, -0.002), (10, -0.01)):
            stage.cue(head={'pitch': pitch}, turn={'pitch': pitch * 0.25}, body={'z': z})
    with stage.section('16_final_chord'):
        stage.cue(head={'pitch': -6}, body={'x': -0.006, 'z': -0.004})
        stage.cue(head={'pitch': 12}, turn={'pitch': 4}, body={'x': 0.012, 'z': -0.012})
        stage.cue(head={'pitch': 4}, turn={'pitch': 1}, body={'x': 0.004, 'z': -0.004})
        stage.cue()
    # Preserve the decimal grid explicitly rather than serializing float roundoff.
    for action in stage.actions:
        action['movement']['duration_s'] = SUBDIVISION_S
    return stage


def document():
    stage = make_stage()
    preparation = pose(1, body_pose={'torso_pose': {}, 'head_orientation': {}})
    preparation['say'] = 'Ich tanze'
    actions = [preparation, *stage.actions, {'music': 'STOP'}]
    actions[1]['music'] = {'song': 'musicfox_hot_dogs_for_breakfast.mp3', 'background': True}
    return {'actions': actions}


def to_yaml():
    return ('# Generated by tools/examples/dance_hot_dogs_for_breakfast.py; edit the recipe.\n'
            '# Shared by dance_standard and dance_hot_dogs_for_breakfast. Start standing.\n'
            '# Prepare before music; 16 phrases x 1.752 s = 28.032 s, then STOP.\n'
            '# Each phrase has four 0.438 s accents; scheduler/audio latency is not compensated.\n'
            '# One foot lifts at a time; all toes return before the final neutral pose.\n' +
            yaml.safe_dump(document(), sort_keys=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--force', action='store_true')
    parser.add_argument('--report', action='store_true')
    args = parser.parse_args()
    try:
        content = to_yaml()
        if args.output:
            with args.output.open('w' if args.force else 'x', encoding='utf-8') as output:
                output.write(content)
        else:
            print(content, end='')
        if args.report:
            print(make_stage().report(), file=sys.stderr)
        print('64 accents; 28.032 s music-window motion, plus preparation and scheduler delays', file=sys.stderr)
    except (ValueError, OSError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
